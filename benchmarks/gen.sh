#!/usr/bin/env bash
# Generate N identical compile-fail UI cases for both frameworks.
#
# Each case is the same one-line type error (`let _: u32 = "…";`, E0308). On the
# subcrate side every case is one `#[subcrate(should_error = "…")]` module in a
# single file; on the trybuild side every case is its own `tests/ui/*.rs` file.
# The literals carry two tokens the runner bumps to force recompiles:
#   VTAG<n>  in every case  — bump to rebuild *all* cases
#   MUTx<n>  in case 1 only — bump to rebuild *one* case
set -euo pipefail

N="${1:-24}"
here="$(cd "$(dirname "$0")" && pwd)"
sub="$here/subcrate-side/tests/ui_bench.rs"
tryui="$here/trybuild-side/tests/ui"

mkdir -p "$(dirname "$sub")" "$tryui"
rm -f "$tryui"/*.rs "$tryui"/*.stderr

{
    echo "// Generated by gen.sh — $N compile-fail cases, one subcrate each. Do not edit."
    echo "use subcrate::subcrate;"
    echo
    for k in $(seq 1 "$N"); do
        if [ "$k" -eq 1 ]; then
            lit="VTAG0 MUTx0 case 1"
        else
            lit="VTAG0 case $k"
        fi
        echo "#[subcrate(should_error = \"mismatched types\")]"
        echo "mod case_$k {"
        echo "    pub fn f() {"
        echo "        let _: u32 = \"$lit\";"
        echo "    }"
        echo "}"
        echo
    done
} >"$sub"

for k in $(seq 1 "$N"); do
    kk=$(printf '%03d' "$k")
    if [ "$k" -eq 1 ]; then
        lit="VTAG0 MUTx0 case 1"
    else
        lit="VTAG0 case $k"
    fi
    cat >"$tryui/case$kk.rs" <<EOF
fn main() {
    let _: u32 = "$lit";
}
EOF
done

echo "generated $N cases (subcrate: 1 file, trybuild: $N files)"
